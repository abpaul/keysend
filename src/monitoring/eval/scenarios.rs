use super::{Level, Past, Plan, Row, Scenario};

const fn level(spend: f64, clicks: f64, impressions: f64, conversions: f64, value: f64) -> Level {
    Level {
        spend,
        clicks,
        impressions,
        conversions,
        value,
    }
}

const fn row(campaign: i64, name: &'static str, clicks: f64, cost: f64, conversions: f64) -> Row {
    Row {
        campaign,
        name,
        clicks,
        cost,
        conversions,
        value: 0.0,
        strength: "",
    }
}

fn plan(id: i64, name: &'static str, channel: &'static str, before: Level, after: Level) -> Plan {
    Plan {
        id,
        name,
        channel,
        before,
        after,
        since: 30,
        year_ago: None,
        lost_to_budget: None,
    }
}

